import * as fs from "node:fs/promises";
import { afterEach, beforeEach, describe, expect, spyOn, test } from "bun:test";
import { mkdir, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { resetUserHome, setUserHome } from "../home";
import { peerDir, peerSecretKeyFile } from "../runtime-names";
import { deriveEndpointId, encodeSecretKey, loadOrCreateIdentity, loadOrCreatePeerId, parseSecretKey } from "./identity";
import { irohAddonLoaderCtx, loadIroh } from "./iroh";

const HEX64 = /^[0-9a-f]{64}$/;

let home: string;

beforeEach(async () => {
  home = await mkdtemp(join(tmpdir(), "ib-peer-identity-"));
  setUserHome(home);
});

afterEach(async () => {
  resetUserHome();
  irohAddonLoaderCtx.reset();
  await rm(home, { recursive: true, force: true });
});

describe("loadOrCreateIdentity", () => {
  test("creates secret.key as 64 lowercase hex plus a newline, mode 0600, in a 0700 directory", async () => {
    const identity = await loadOrCreateIdentity();
    const text = await readFile(peerSecretKeyFile(), "utf-8");
    expect(text).toMatch(/^[0-9a-f]{64}\n$/);
    expect(text).toBe(encodeSecretKey(identity.secretKey));
    expect(identity.secretKey.length).toBe(32);
    expect(identity.id).toMatch(HEX64);
    expect(identity.id).toBe(deriveEndpointId(identity.secretKey));
    expect((await stat(peerSecretKeyFile())).mode & 0o777).toBe(0o600);
    expect((await stat(peerDir())).mode & 0o777).toBe(0o700);
  });

  test("does not change the mode of ~/.itsybitsy when it has to create it", async () => {
    await loadOrCreateIdentity();
    expect((await stat(join(home, ".itsybitsy"))).mode & 0o777).not.toBe(0o700);
  });

  test("returns the same identity on every later call and never rewrites the file", async () => {
    const first = await loadOrCreateIdentity();
    const before = await stat(peerSecretKeyFile());
    const second = await loadOrCreateIdentity();
    expect(second.id).toBe(first.id);
    expect(second.secretKey).toEqual(first.secretKey);
    expect((await stat(peerSecretKeyFile())).mtimeMs).toBe(before.mtimeMs);
    expect(await loadOrCreatePeerId()).toBe(first.id);
  });

  test("concurrent first calls agree on one key", async () => {
    const results = await Promise.all(Array.from({ length: 12 }, () => loadOrCreateIdentity()));
    const ids = new Set(results.map((r) => r.id));
    expect(ids.size).toBe(1);
    const text = await readFile(peerSecretKeyFile(), "utf-8");
    expect(deriveEndpointId(parseSecretKey(text, "secret.key"))).toBe(results[0]!.id);
  });

  test("reads an existing key file, tolerating surrounding whitespace", async () => {
    const seed = new Uint8Array(32).fill(7);
    await mkdir(peerDir(), { recursive: true });
    await writeFile(peerSecretKeyFile(), `  ${Buffer.from(seed).toString("hex")}\n\n`);
    const identity = await loadOrCreateIdentity();
    expect(identity.secretKey).toEqual(seed);
    expect(identity.id).toBe(deriveEndpointId(seed));
  });

  test("a malformed key file is an error and is left untouched", async () => {
    await mkdir(peerDir(), { recursive: true });
    for (const bad of ["not hex\n", "AB".repeat(32) + "\n", "ab".repeat(31) + "\n"]) {
      await writeFile(peerSecretKeyFile(), bad);
      await expect(loadOrCreateIdentity()).rejects.toThrow("is not 64 lowercase hex characters");
      expect(await readFile(peerSecretKeyFile(), "utf-8")).toBe(bad);
    }
  });

  test("an empty key file that stays empty is an error after the retries", async () => {
    await mkdir(peerDir(), { recursive: true });
    await writeFile(peerSecretKeyFile(), "");
    await expect(loadOrCreateIdentity()).rejects.toThrow("is not 64 lowercase hex characters");
  });

  test("an empty key file that is filled in shortly is read once it is", async () => {
    const seed = new Uint8Array(32).fill(9);
    await mkdir(peerDir(), { recursive: true });
    await writeFile(peerSecretKeyFile(), "");
    setTimeout(() => void writeFile(peerSecretKeyFile(), encodeSecretKey(seed)), 30);
    expect((await loadOrCreateIdentity()).id).toBe(deriveEndpointId(seed));
  });

  test("never loads the iroh addon", async () => {
    let loads = 0;
    irohAddonLoaderCtx.set(async () => {
      loads++;
      throw new Error("the addon must not be loaded");
    });
    await loadOrCreateIdentity();
    await loadOrCreateIdentity();
    expect(loads).toBe(0);
  });
});

describe("node:crypto id derivation matches iroh", () => {
  test("a key generated by iroh gets the same id from node:crypto", async () => {
    const iroh = await loadIroh();
    const key = iroh.SecretKey.generate();
    await mkdir(peerDir(), { recursive: true });
    await writeFile(peerSecretKeyFile(), encodeSecretKey(key.toBytes()));
    const identity = await loadOrCreateIdentity();
    expect(identity.id).toBe(key.public().toString());
  });

  test("a key created here gets the same id from iroh", async () => {
    const iroh = await loadIroh();
    const identity = await loadOrCreateIdentity();
    expect(iroh.SecretKey.fromBytes(identity.secretKey).public().toString()).toBe(identity.id);
  });

  test("deriveEndpointId rejects a seed that is not 32 bytes", () => {
    expect(() => deriveEndpointId(new Uint8Array(31))).toThrow("32 bytes, got 31");
  });
});

test("a suspended identity publisher exposes only a complete winning key", async () => {
  const paused = Promise.withResolvers<void>(), resume = Promise.withResolvers<void>();
  const link = fs.link;
  let held = false;
  const publish = spyOn(fs, "link").mockImplementation(async (from, to) => {
    if (!held && to === peerSecretKeyFile()) {
      held = true;
      expect(String(from)).toContain("/sealed/.key-staging/");
      expect((await stat(from)).mode & 0o777).toBe(0o600);
      paused.resolve(); await resume.promise;
    }
    await link(from, to);
  });
  try {
    const first = loadOrCreateIdentity();
    await paused.promise;
    expect(await Bun.file(peerSecretKeyFile()).exists()).toBe(false);
    const winner = await loadOrCreateIdentity();
    resume.resolve();
    expect((await first).id).toBe(winner.id);
    expect((await stat(peerSecretKeyFile())).nlink).toBe(1);
    expect(await fs.readdir(join(home, ".itsybitsy/sealed/.key-staging"))).toEqual([]);
  } finally { resume.resolve(); publish.mockRestore(); }
});

test("cross-device identity publication leaves no key or temporary secret", async () => {
  const fail = spyOn(fs, "link").mockRejectedValue(Object.assign(Error("cross-device link"), { code: "EXDEV" }));
  try {
    await expect(loadOrCreateIdentity()).rejects.toMatchObject({ code: "EXDEV" });
    expect(await Bun.file(peerSecretKeyFile()).exists()).toBe(false);
    expect(await fs.readdir(join(home, ".itsybitsy/sealed/.key-staging"))).toEqual([]);
  } finally { fail.mockRestore(); }
});

test("identity load removes an interrupted dead publisher's extra link", async () => {
  const { writeTransferOwner } = await import("./transfer-owner");
  const { isPidAliveCtx } = await import("../agents");
  const original = await loadOrCreateIdentity();
  const dir = join(home, ".itsybitsy/sealed/.key-staging", crypto.randomUUID());
  await mkdir(dir);
  await writeTransferOwner(dir, { pid: 42, start: 10 });
  await fs.link(peerSecretKeyFile(), join(dir, "key"));
  isPidAliveCtx.set(pid => pid !== 42);
  try {
    expect((await loadOrCreateIdentity()).id).toBe(original.id);
    expect((await stat(peerSecretKeyFile())).nlink).toBe(1);
    expect(await fs.readdir(join(home, ".itsybitsy/sealed/.key-staging"))).toEqual([]);
  } finally { isPidAliveCtx.reset(); }
});
